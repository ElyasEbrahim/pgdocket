"""How many audit labels could the model's scores save? (#41, no API calls)

`pgdocket audit` bets on blind labels alone. Prediction-powered methods (PPI and PPI++, prediction-powered e-values,
prediction-powered risk monitoring) would use the model's score on every accepted row as a control variate: for each
audited row, its label minus a multiple of its score, plus the mean score over every accepted row of the batch (known
exactly). Variance decides how many labels an e-process needs, and at best the scores remove the share corr(score,
right)^2 of one label's variance, the correlation taken over the accepted rows. So 1 / (1 - corr^2) bounds how many
times fewer labels any such design can need, before the cost of the wider bets it must allow. Drawing the least-sure
rows more often, with inverse-probability weights, is bounded under calibration by E[p(1-p)] + var(p) against
(E sqrt(p(1-p)))^2.

Streams: the live Kubernetes decision (its stored calibration, 90 %), and the CFPB complaints of 2022-2023 calibrated
on 2015-2021 at 85 % (the stream `jevbench auditvalidate` audits), and at 80 % and 75 % for comparison.
"""
import json
import os

import numpy as np

from pgdocket import calibration
from pgdocket.spec import read_answer

from .db import connect
from .report import load_run

OUT = "results/audit-scores"


def ceilings(p, right=None):
    """Bounds on how many times fewer audit labels the scores could need. `p`: the calibrated confidence of each
    accepted row; `right`: whether its answer is right (for the bound measured with labels)."""
    p = np.asarray(p, float)
    alone, scores = p.var() + (p * (1 - p)).mean(), (p * (1 - p)).mean()
    tilted = np.sqrt(p * (1 - p)).mean() ** 2
    out = {"rows": int(len(p)), "quantiles": [float(x) for x in np.quantile(p, [0, 0.1, 0.5, 0.9])],
           "share_at_top": float(np.mean(np.isclose(p, p.max()))),
           "model_scores": float(alone / scores) if scores > 0 else 1.0,
           "model_tilted": float(alone / tilted) if tilted > 0 else 1.0}
    if right is not None:
        y = np.asarray(right, float)
        r = float(np.corrcoef(p, y)[0, 1]) if p.std() > 0 and y.std() > 0 else 0.0
        out |= {"precision": float(y.mean()), "corr": r, "labels": float(1 / (1 - r * r))}
    return out


def streams():
    out = {}
    with connect() as conn:
        spec, cal = conn.execute("SELECT v.spec, v.calibration FROM docket.version v JOIN docket.decision d ON "
                                 "d.id = v.decision_id WHERE d.name = 'k8s_route' AND v.version = d.active_version").fetchone()
        rows = conn.execute("SELECT c.row_key, j.answer, l.sig FROM docket.current c JOIN docket.decision d ON d.id = "
                            "c.decision_id JOIN docket.judgment j ON j.id = c.judgment_id JOIN demo.k8s_live l ON "
                            "l.number::text = c.row_key WHERE d.name = 'k8s_route' AND c.version = d.active_version").fetchall()
        _, exps, answers, truth = load_run(conn, "jev-20261017-122314")
        dates = dict(conn.execute("SELECT text_hash, date_received FROM bench.complaints").fetchall())
    acc = [(a, sig) for _, a, sig in rows if calibration.auto(a, spec, cal)]
    out["Kubernetes, the live decision (90 %)"] = ceilings([calibration.calibrated(a, spec, cal) for a, _ in acc],
                                                           [read_answer(spec, a)[0] == sig for a, sig in acc])
    opts = exps["choice_base"]["options"]
    cspec = {"kind": "choice", "question": "Which product is the complaint about?", "options": [{"name": o} for o in opts]}
    dated = sorted((dates[h], h) for h in answers["choice_base"] if h in truth and dates.get(h))
    early = [h for d, h in dated if d.year <= 2021]
    late = [h for d, h in dated if d.year >= 2022]
    for target in (0.85, 0.80, 0.75):
        c = calibration.fit(cspec, [answers["choice_base"][h] for h in early], [truth[h].product for h in early], target)
        acc = [h for h in late if calibration.auto(answers["choice_base"][h], cspec, c)]
        name = f"CFPB 2022–2023, calibrated on 2015–2021 at {100 * target:.0f} %" + (" (audited in #23)" if target == 0.85 else "")
        out[name] = ceilings([calibration.calibrated(answers["choice_base"][h], cspec, c) for h in acc],
                             [read_answer(cspec, answers["choice_base"][h])[0] == truth[h].product for h in acc])
        out[name]["threshold"] = c["threshold"]
    return out


def run():
    res = {"streams": streams()}
    os.makedirs(OUT, exist_ok=True)
    with open(f"{OUT}/results.json", "w") as f:
        json.dump(res, f, indent=2)
    with open(f"{OUT}/report.md", "w") as f:
        f.write(render(res))
    return OUT


def render(res):
    L = ["# How many audit labels could the model's scores save?", "",
         "No API calls. Generated by `jevbench auditscores` (#41). A prediction-powered audit uses each accepted row's score as "
         "a control variate. At best that removes the share corr(score, right)² of one label's variance (over the accepted "
         "rows), so 1 / (1 − corr²) bounds how many times fewer labels it can need, before the cost of the wider bets it "
         "must allow. Drawing the least-sure rows more often is bounded, under calibration, by E[p(1−p)] + var(p) against "
         "(E√(p(1−p)))².", "",
         "| accepted rows of | rows | precision | calibrated confidence, 0 / 10 / 50 / 90 % | at the top value | "
         "corr(confidence, right) | fewer labels at best, from the scores | if calibrated | drawing the least-sure rows more |",
         "| --- | ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: |"]
    for name, s in res["streams"].items():
        q = " / ".join(f"{x:.3f}" for x in s["quantiles"])
        L.append(f"| {name} | {s['rows']} | {100 * s['precision']:.1f} % | {q} | {100 * s['share_at_top']:.0f} % | "
                 f"{s['corr']:.2f} | {s['labels']:.2f}× | {s['model_scores']:.2f}× | {s['model_tilted']:.2f}× |")
    L += ["", "Jev's probabilities pile up at the top, so most accepted rows share one calibrated confidence, and the score "
              "says little about which of them are wrong. Nothing is built (#41)."]
    return "\n".join(L) + "\n"
