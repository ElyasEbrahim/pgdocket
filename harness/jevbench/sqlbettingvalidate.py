"""Betting intervals in SQL (#32, no API calls): docket.betting_interval against pgdocket.betting.interval.

docket.estimate() now gives a rare answer below the floor a betting interval itself (migration 012). The SQL finds the
interval's ends by bisection, the Python tests every candidate share; this checks they agree, on random labels from
scopes of 40 rows to a million and on the live k8s_route decision, and times the SQL. It runs in a throwaway database
(set DATABASE_URL to a role that may create one).
"""
import json
import os
import time
import uuid

import numpy as np

from pgdocket import betting, ledger

OUT = "results/sql-betting"
SCOPES = (40, 300, 2000, 4000, 4001, 20000, 1_000_000)
LABELS = (1, 5, 20, 60, 150, 400, 1200)
SHARES = (0.002, 0.01, 0.03, 0.1, 0.3, 0.6)


def cases(rng, count):
    """Random labels (y, f), the model's total, the scope's rows and α."""
    out = []
    for _ in range(count):
        N = int(rng.choice(SCOPES))
        n = int(min(N - 1, rng.choice(LABELS)))
        share = float(rng.choice(SHARES))
        y = (rng.random(n) < share).astype(float)
        f = np.where(rng.random(n) < float(rng.choice([0.6, 0.9, 0.99])), y, 1 - y)
        total = max(float(f.sum()), float(round(N * min(1.0, share * rng.uniform(0.5, 1.5)))))
        out.append((y, f, total, N, float(rng.choice([0.05, 0.1]))))
    out += [(np.zeros(30), np.zeros(30), 0.0, 1000, 0.05),                       # no row with the answer
            (np.r_[np.ones(5), np.zeros(45)], np.r_[np.ones(5), np.zeros(45)], 5.0, 50, 0.05),   # all but none labelled
            (np.ones(4), np.ones(4), 4.0, 4, 0.05)]                             # every row labelled
    return out


def run(count=300, seed=32):
    import psycopg
    from psycopg.conninfo import make_conninfo
    base = os.environ["DATABASE_URL"]
    db = "sqlbetting_" + uuid.uuid4().hex[:6]
    with psycopg.connect(base, autocommit=True) as su:
        su.execute(f"CREATE DATABASE {db}")
    try:
        dsn = make_conninfo(base, dbname=db)
        ledger.install(dsn)
        rng = np.random.default_rng(seed)
        res = {"cases": 0, "identical": 0, "one_step": 0, "further": 0, "both_empty": 0, "mismatched_empty": 0,
               "sql_seconds": 0.0, "python_seconds": 0.0, "timing": []}
        with psycopg.connect(dsn) as c:
            for y, f, total, N, alpha in cases(rng, count):
                t0 = time.perf_counter()
                want = betting.interval(y, f, total, N, alpha)
                t1 = time.perf_counter()
                got = c.execute("SELECT docket.betting_interval(%s::float8[], %s::float8[], %s, %s, %s)",
                                ([float(x) for x in y], [float(x) for x in f], total, N, alpha)).fetchone()[0]
                t2 = time.perf_counter()
                res["cases"] += 1
                res["python_seconds"] += t1 - t0
                res["sql_seconds"] += t2 - t1
                if want is None or got is None:
                    res["both_empty" if want is None and got is None else "mismatched_empty"] += 1
                    continue
                step = 1 / N if N + 1 <= betting.GRID else 1 / (betting.GRID - 1)
                d = max(abs(want[0] - got[0]), abs(want[1] - got[1]))
                res["identical" if d < 1e-12 else "one_step" if d <= step + 1e-12 else "further"] += 1
            for N, n in ((3000, 1499), (1_000_000, 2000), (1_000_000, 10000)):   # a rare answer, many labels
                y = (rng.random(n) < 0.002).astype(float)
                f = np.where(rng.random(n) < 0.9, y, 1 - y)
                t0 = time.perf_counter()
                c.execute("SELECT docket.betting_interval(%s::float8[], %s::float8[], %s, %s)",
                          ([float(x) for x in y], [float(x) for x in f], N * 0.002, N)).fetchone()
                res["timing"].append({"rows": N, "labels": n, "seconds": time.perf_counter() - t0})
    finally:
        with psycopg.connect(base, autocommit=True) as su:
            su.execute(f"DROP DATABASE IF EXISTS {db} WITH (FORCE)")
    os.makedirs(OUT, exist_ok=True)
    with open(f"{OUT}/results.json", "w") as fh:
        json.dump(res, fh, indent=2)
    with open(f"{OUT}/report.md", "w") as fh:
        fh.write(render(res))
    return OUT


def render(res):
    L = ["# Betting intervals in SQL", "",
         "No API calls. Generated by `jevbench sqlbettingvalidate` (#32): `docket.betting_interval` (migration 012, "
         "the ends found by bisection) against `pgdocket.betting.interval` (every candidate share tested), on random "
         f"labels: scopes of {SCOPES[0]:,} to {SCOPES[-1]:,} rows, {LABELS[0]:,} to {LABELS[-1]:,} labels, answers on "
         f"{100 * SHARES[0]:.1f} % to {100 * SHARES[-1]:.0f} % of rows, models right on 60–99 % of them, α = 0.05 or "
         "0.1, and three edge cases.", "",
         "| cases | identical | one candidate apart | further | empty both ways | empty one way |",
         "| ---: | ---: | ---: | ---: | ---: | ---: |",
         f"| {res['cases']} | {res['identical']} | {res['one_step']} | {res['further']} | {res['both_empty']} | "
         f"{res['mismatched_empty']} |", "",
         "The random cases draw the model's total over the scope independently of its answers on the labelled rows, so "
         "some are inconsistent, and there every share is rightly rejected. This checks that the two agree, not how "
         "often the interval holds (#30 and #31 measured that).", "",
         f"Time for all cases: SQL {res['sql_seconds']:.2f} s, Python {res['python_seconds']:.2f} s.", "",
         "| rows in scope | labels (a 0.2 % answer) | SQL |", "| ---: | ---: | ---: |"]
    L += [f"| {t['rows']:,} | {t['labels']:,} | {1000 * t['seconds']:.0f} ms |" for t in res["timing"]]
    return "\n".join(L) + "\n"
