"""Do recall targets hold on real model errors? (#21, no API calls)

Three yes/no tasks with stored answers and known labels: Kubernetes "is it a feature request?" (500 issues judged by
`pgdocket check`) and two Phase 0 CFPB questions (2,000 complaints each). Each set of judged rows stands in for the
population. Labels are drawn at random from it (with replacement), the recall threshold is chosen as `calibrate
--recall-target` would choose it, and the true recall is measured on the whole population: the share of real yeses
the model's score keeps at or above the threshold. A failure is a threshold whose true recall is below the target;
the method promises at most 5 % of trials.
"""
import json
import os

import numpy as np

from pgdocket.metrics import recall_threshold

from .db import connect

OUT = "results/recall-validation"
TARGETS = (0.8, 0.9, 0.95)
BUDGETS = (100, 200, 400)


def load_check(folder, positive):
    rows = [json.loads(line) for line in open(f"results/{folder}/judgments.jsonl")]
    return np.array([float(r["answer"]["noul"]) for r in rows]), np.array([r["label"] == positive for r in rows])


def load_phase0(experiment, run="jev-20261017-122314"):
    from .report import load_run
    from .tasks import noul_truth
    with connect() as conn:
        _, exps, answers, truth = load_run(conn, run)
    family, ans = exps[experiment]["family"], answers[experiment]
    hs = [h for h in ans if h in truth]
    return (np.array([float(ans[h]["noul"]) for h in hs]),
            np.array([bool(noul_truth(family, truth[h])) for h in hs]))


def validate(p, y, trials=1000, seed=0):
    rng = np.random.default_rng(seed)
    out = {"rows": len(y), "yeses": int(y.sum()), "prevalence": float(y.mean()), "targets": {}}
    for target in TARGETS:
        cands = np.unique(p)
        best = max((float((p < t).mean()) for t in cands if (p[y] >= t).mean() >= target), default=0.0)
        res = {"ideal_dismissed": best, "by_labels": {}}
        for n in BUDGETS:
            found = fails = 0
            dismissed = []
            for _ in range(trials):
                idx = rng.integers(0, len(y), n)
                c = recall_threshold(p[idx], y[idx], target)["chosen"]
                if c is None:
                    continue
                found += 1
                fails += (p[y] >= c["threshold"]).mean() < target
                dismissed.append(float((p < c["threshold"]).mean()))
            res["by_labels"][n] = {"found": found / trials, "failure_rate": fails / trials,
                                   "mean_dismissed": float(np.mean(dismissed)) if dismissed else 0.0}
        out["targets"][target] = res
    return out


def render(results):
    pct = lambda x: f"{100 * x:.1f} %"
    L = ["# Do recall targets hold on real model errors?", "",
         "No API calls. Generated by `jevbench recallvalidate`. Each task's judged rows stand in for the population; "
         "1,000 random label draws per cell. *Answered no* is the share of all rows below the chosen threshold, which "
         "`auto` would answer *no* without review. *Failure* is a threshold whose true recall is below the target "
         "(at most 5 % promised). *Ideal* is the largest share that could be answered *no* if every label were known.", ""]
    for name, r in results.items():
        L += [f"## {name}", "", f"{r['rows']:,} judged rows, {r['yeses']:,} real yeses ({pct(r['prevalence'])}).", "",
              "| keep at least | labels | threshold found | failures | answered no (mean) | ideal |",
              "| ---: | ---: | ---: | ---: | ---: | ---: |"]
        for target, t in r["targets"].items():
            for n, b in t["by_labels"].items():
                L.append(f"| {pct(float(target))} of yeses | {n} | {pct(b['found'])} | {pct(b['failure_rate'])} | "
                         f"{pct(b['mean_dismissed'])} | {pct(t['ideal_dismissed'])} |")
        L.append("")
    return "\n".join(L)


def run():
    results = {
        "Kubernetes: is it a feature request?": validate(*load_check("check-k8s-feature", "feature")),
        "CFPB: is it about debt collection?": validate(*load_phase0("noul_debt_collection")),
        "CFPB: is it about an incorrect credit report?": validate(*load_phase0("noul_incorrect_report")),
    }
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "results.json"), "w") as f:
        json.dump(results, f, indent=2, default=float)
    with open(os.path.join(OUT, "report.md"), "w") as f:
        f.write(render(results))
    return OUT
